function useSound() {
  const [muted, setMuted] = useState(() => localStorage.getItem('azkar_muted') === '1');
  const ctxRef = useRef(null);
  const mutedRef = useRef(muted);
  mutedRef.current = muted;

  const ctx = () => {
    if (!ctxRef.current) {
      try { ctxRef.current = new (window.AudioContext || window.webkitAudioContext)(); } catch (e) {}
    }
    return ctxRef.current;
  };
  const tone = (f, at, dur, type = 'sine', g = 0.06) => {
    if (mutedRef.current) return;
    const c = ctx();
    if (!c) return;
    try {
      const o = c.createOscillator();
      const gn = c.createGain();
      o.type = type;
      o.frequency.value = f;
      const t0 = c.currentTime + at;
      gn.gain.setValueAtTime(0.0001, t0);
      gn.gain.exponentialRampToValueAtTime(g, t0 + 0.012);
      gn.gain.exponentialRampToValueAtTime(0.0001, t0 + dur);
      o.connect(gn);
      gn.connect(c.destination);
      o.start(t0);
      o.stop(t0 + dur + 0.06);
    } catch (e) {}
  };

  return {
    muted,
    toggle: () => setMuted((m) => { localStorage.setItem('azkar_muted', m ? '0' : '1'); return !m; }),
    tap: () => tone(620, 0, 0.05, 'sine', 0.045),
    done: () => { tone(523, 0, 0.1, 'sine', 0.06); tone(784, 0.09, 0.16, 'sine', 0.06); },
    fanfare: () => {
      tone(523, 0, 0.14); tone(659, 0.11, 0.14); tone(784, 0.22, 0.16); tone(1047, 0.34, 0.4, 'sine', 0.07);
    },
  };
}

