/* نص الذكر/الآية — يتقلص تلقائيًا ليتسع دون تمرير، ومضمون الظهور دائمًا */
/* يعيد القياس عند تحميل الخطوط وتغيير المقاس حتى لا يختفي النص أبدًا   */
/* ------------------------------------------------------------------ */
function FitText({ text, q, max, min, dir }) {
  const ref = useRef(null);
  const innerRef = useRef(null);

  useLayoutEffect(() => {
    const el = ref.current;
    const inner = innerRef.current;
    if (!el || !inner) return;

    const fit = () => {
      // ابدأ من الحجم الأقصى دائمًا ثم قلّص تدريجيًا
      let s = max;
      inner.style.transform = 'none';
      el.style.fontSize = s + 'px';
      let guard = 60;
      const over = () => el.scrollHeight > el.clientHeight + 1 || el.scrollWidth > el.clientWidth + 1;
      while (s > min && guard-- > 0 && over()) {
        s -= 0.5;
        el.style.fontSize = s + 'px';
      }
      // إن بقي فائض بعد الوصول للحد الأدنى: قلّص بالمقياس حتى يظهر كله
      if (over() && el.clientHeight > 40) {
        const k = Math.min(1, el.clientHeight / el.scrollHeight);
        if (k > 0.3 && k < 1) inner.style.transform = `scale(${k})`;
      }
    };

    fit();
    // إعادة القياس عند اكتمال تحميل الخطوط (سبب رئيسي لاختفاء/تضخم النص سابقًا)
    try {
      if (document.fonts && document.fonts.ready) document.fonts.ready.then(() => fit()).catch(() => {});
      if (document.fonts && document.fonts.addEventListener) {
        const onDone = () => fit();
        document.fonts.addEventListener('loadingdone', onDone);
        return () => document.fonts.removeEventListener('loadingdone', onDone);
      }
    } catch (e) {}
    // شبكة أمان: قياسات متأخرة بعد أول رسم
    const t1 = setTimeout(fit, 350);
    const t2 = setTimeout(fit, 1000);
    return () => { clearTimeout(t1); clearTimeout(t2); };
  }, [text, max, min]);

  return (
    <div
      ref={ref}
      className={q ? 'quran-text' : 'dhikr-text'}
      style={{
        flex: 1, minHeight: 0, width: '100%', overflow: 'hidden',
        display: 'flex', alignItems: 'center', justifyContent: 'center',
        textAlign: 'center', padding: '2px 0', direction: dir,
      }}
    >
      <span ref={innerRef} style={{ display: 'block', width: '100%', transformOrigin: 'center center' }}>
        {text}
      </span>
    </div>
  );
}

