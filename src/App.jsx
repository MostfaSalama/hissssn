  if (/قرآن/.test(rule)) return { label: g('gradeQuran'), color: p.accent };
  if (/شاذ|ضعيف|منكر/.test(txt)) return { label: g('gradeWeak'), color: p.warn };
  if (/صحيح/.test(txt) && /حسن/.test(txt)) return { label: g('gradeHasanSahih'), color: p.teal };
