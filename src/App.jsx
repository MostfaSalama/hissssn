const scheduleAzkarNotifs = async (opts = {}) => {
  const { morning = true, evening = true, lang = 'ar' } = opts;
  const N = NOTIF_STR[lang] || NOTIF_STR.ar;
  const { fajr, asr, dhuhr, maghrib } = await getPrayerTimes(lang);
  const { LocalNotifications } = await import('@capacitor/local-notifications');
  const addMin = (d, m) => new Date(d.getTime() + m*60000);

  // لُغنا كل التنبيهات القديمة (الصباح والمساء) معًا
  const oldIds = [];
  if (morning) oldIds.push(...MORNING_IDS);
  if (evening) oldIds.push(...EVENING_IDS);
  oldIds.push(300, 301, 302);
  await cancelNumericNotifs(LocalNotifications, oldIds);

  const notifs = [];

  // === الصباح: فجر+10د ثم كل 90 دقيقة حتى الظهر (14:00) ===
  if (morning) {
    const morningStart = addMin(fajr, 10);
    const morningEnd = new Date(fajr); morningEnd.setHours(14, 0, 0, 0);
    const morningPoints = buildWindowPoints(morningStart, morningEnd, 90);
    morningPoints.forEach((p, idx) => {
      notifs.push({
        id: MORNING_IDS[idx],
        title: N.titleM,
        body: idx === 0 ? N.bodyM0 : (idx % 2 === 0 ? N.bodyM : N.notifAzkarM),
        schedule: { at: p.toISOString(), repeats: true, every: 'day' },
        smallIcon: 'ic_stat_hissn', largeIcon: 'ic_launcher', iconColor: '#C79A4F', channelId: 'hissn_azkar', sound: 'hissn_notif.wav',
      });
    });
  }

  // === المساء: عصر+10د ثم كل 90 دقيقة حتى 01:00 من اليوم التالي ===
  if (evening) {
    const eveningStart = addMin(asr, 10);
    const eveningEnd = addMin(asr, 10); eveningEnd.setDate(eveningEnd.getDate()+1); eveningEnd.setHours(1, 0, 0, 0);
    const eveningPoints = buildWindowPoints(eveningStart, eveningEnd, 90);
    eveningPoints.forEach((p, idx) => {
      notifs.push({
        id: EVENING_IDS[idx],
        title: N.titleE,
        body: idx === 0 ? N.bodyE0 : (idx % 2 === 0 ? N.bodyE : N.notifAzkarE),
        schedule: { at: p.toISOString(), repeats: true, every: 'day' },
        smallIcon: 'ic_stat_hissn', largeIcon: 'ic_launcher', iconColor: '#E3BC7A', channelId: 'hissn_azkar', sound: 'hissn_notif.wav',
      });
    });
  }

  // === الجمعة: 3 تنبيهات ليوم واحد فقط (غسل + كهف + ساعة استجابة) ===
  if (isFriday()) {
    const nowMs = new Date().getTime();
    const fri = [
      { id: 300, title: N.titleM, body: N.friGhusl, at: addMin(fajr, 10), iconColor: '#C79A4F' },
      { id: 301, title: N.titleM, body: N.friKahf, at: addMin(dhuhr, 45), iconColor: '#C79A4F' },
      { id: 302, title: N.titleE, body: N.friDua, at: new Date((asr.getTime() + maghrib.getTime()) / 2), iconColor: '#E3BC7A' },
    ];
    fri.forEach((f) => {
      if (f.at.getTime() > nowMs) {
        notifs.push({ id: f.id, title: f.title, body: f.body, schedule: { at: f.at.toISOString() }, smallIcon: 'ic_stat_hissn', largeIcon: 'ic_launcher', iconColor: f.iconColor, channelId: 'hissn_azkar', sound: 'hissn_notif.wav' });
      }
    });
  }

  if (notifs.length) await LocalNotifications.schedule({ notifications: notifs });
};

const setupAzkarNotifications = async (lang = 'ar') => {
  const isNative = (() => { try { return window.Capacitor && window.Capacitor.isNativePlatform && window.Capacitor.isNativePlatform(); } catch (e) { return false; } })();
  if (isNative) {
    try {
      const { LocalNotifications } = await import('@capacitor/local-notifications');
      const perm = await LocalNotifications.requestPermissions();
      if (perm.display !== 'granted') return;
      try {
        const ST = STR[lang] || STR.ar;
        await LocalNotifications.createChannel({
          id: 'hissn_azkar',
          name: ST.channelName || 'Azkar',
          description: ST.channelDesc || '',
          sound: 'hissn_notif.wav',
          vibration: true,
        });
      } catch (e) {}
      // عند إعادة الفتح: إن كانت إحدى الفترتين مكتملة اليوم، لا نعيد جدولة إشعاراتها
      const today = dateStr();
      let done = {};
      try { done = JSON.parse(localStorage.getItem('azkar_done') || '{}'); } catch (e) {}
      const morningDone = done.morning === today;
      const eveningDone = done.evening === today;
      if (morningDone) await cancelPeriodNotifs('morning');
      if (eveningDone) await cancelPeriodNotifs('evening');
      await scheduleAzkarNotifs({ morning: !morningDone, evening: !eveningDone, lang });
    } catch (e) {}
    return;
  }
  if ('Notification' in window && Notification.permission !== 'denied') {
    try { if (Notification.permission === 'default') await Notification.requestPermission(); } catch (e) {}
  }
};

